function uniqById(items: Array<ExerciseCatalogItem | null | undefined>) {
  const map = new Map<string, ExerciseCatalogItem>();
  let dropped = 0;
  for (const it of items) {
    if (!it || typeof (it as any).id !== 'string' || !(it as any).id.trim()) {
      dropped++;
      continue;
    }
    map.set((it as any).id, it as ExerciseCatalogItem);
  }
  if (__DEV__ && dropped > 0) {
    // eslint-disable-next-line no-console
    console.warn(`[FORGE][ERROR] exerciseCatalog dropped ${dropped} invalid entries`);
  }
  return Array.from(map.values());
}


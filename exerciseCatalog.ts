export const SEM_ROLE_DEFAULT_WEIGHTS = {
  agonist: 1.0,
  synergist: 0.5,
  stabilizer: 0.25,
} as const;

function normalizeText(s: any): string {
  return String(s ?? '')
    .trim()
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

export function findCatalogItemById(id: any): ExerciseCatalogItem | null {
  if (typeof id !== 'string') return null;
  const t = id.trim();
  if (!t) return null;
  return EXERCISE_CATALOG.find((x) => x.id === t) ?? null;
}

export function findCatalogItemByNameOrAlias(name: any): ExerciseCatalogItem | null {
  const q = normalizeText(name);
  if (!q) return null;

  for (const item of EXERCISE_CATALOG) {
    if (normalizeText(item.name) === q) return item;

    if (Array.isArray(item.aliases)) {
      for (const a of item.aliases) {
        if (normalizeText(a) === q) return item;
      }
    }
  }
  return null;
}

export function getSemMetaForExercise(ex: ExerciseCatalogItem): {
  semRomTag: 'partial' | 'full' | 'lengthened';
  semMuscles: { muscle: string; role: 'agonist' | 'synergist' | 'stabilizer'; weight: number }[];
} {
  const semRomTag = (ex as any).semRomTag ?? 'full';

  const semMusclesRaw =
    (ex as any).semMuscles && (ex as any).semMuscles.length > 0
      ? (ex as any).semMuscles
      : [
          // Default: primary muscle is the agonist.
          { muscle: ex.primaryMuscle, role: 'agonist' as const, weight: SEM_ROLE_DEFAULT_WEIGHTS.agonist },
        ];

  const semMuscles = semMusclesRaw.map((m: any) => ({
    muscle: String(m.muscle),
    role: m.role as 'agonist' | 'synergist' | 'stabilizer',
    weight: typeof m.weight === 'number' ? m.weight : SEM_ROLE_DEFAULT_WEIGHTS[m.role as keyof typeof SEM_ROLE_DEFAULT_WEIGHTS],
  }));

  return { semRomTag, semMuscles };
}

